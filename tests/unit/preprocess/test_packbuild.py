def test_videos_labels_pairs_and_provenance(demo):
    out = demo["pack"] / "packdemo"
    build_dataset("packdemo", out=out)

    videos = read_jsonl(out / "videos.jsonl.gz", VideoRecord)
    records = read_inventory("packdemo", demo["work"])
    assert [v.key for v in videos] == [r.key for r in records]
    assert videos[0] == VideoRecord(
        key="FS_A/p00_p01",
        compression=None,
        label_key="PD-FS_A",
        method="SwapA",
        identity="p00",
        source_id="p01",
        target_id="p00",
        pair_key="p00",
        attrs={"task_name": "Swapper A"},
    )

    labels = yaml.safe_load((out / "labels.yaml").read_text("utf-8"))
    assert labels["vocab"]["PD-FS_B"] == {
        "binary": 1,
        "binary_av": 1,
        "family": "face-swap",
        "method": "SwapB",
        "multiclass": 2,
        "task": "FS_B",
    }

    pairs = read_jsonl(out / "pairs.jsonl.gz", PairRecord)
    assert len(pairs) == 20
    assert PairRecord("FS_B/p09_p01", "REAL/p09", "target-id") in pairs

    provenance = PackProvenance.model_validate_json((out / "PROVENANCE.json").read_text("utf-8"))
    listing = "".join(sorted(f"{r.key}\t{r.compression or ''}\t{r.relpath}\n" for r in records))
    assert provenance.builder == {"id": "packdemo", "version": "1"}
    assert provenance.dfwb == __version__
    assert provenance.source_listing_sha256 == sha256_text(listing)
    assert provenance.rules["official"] == {"rule": "official", "params": {}}
    assert provenance.rules["benchmark"]["params"]["pool"] == "official-test"
    assert set(provenance.rules) == {"official", "ident-72-14-14", "all-test", "benchmark"}


