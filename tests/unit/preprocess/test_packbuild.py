class PackDemoBuilder(BaseBuilder):
    """Reals ``originals/<id>``; fakes ``swap_a|swap_b/<target>_<source>``; splits in JSON."""

    dataset_id = "packdemo"
    expected_folder = "PackDemo"
    label_prefix = "PD"
    tasks = (
        TaskSpec("REAL", "Originals", "real", "originals", "original"),
        TaskSpec("FS_A", "Swapper A", "fake", "swap_a", "SwapA"),
        TaskSpec("FS_B", "Swapper B", "fake", "swap_b", "SwapB"),
    )
    metadata_files = (_SPLITS_FILE,)
    labels = {
        "REAL": LabelSpec(binary=0, binary_av=0, multiclass=0, family="real"),
        "FS_A": LabelSpec(binary=1, binary_av=1, multiclass=1, family="face-swap"),
        "FS_B": LabelSpec(binary=1, binary_av=1, multiclass=2, family="face-swap"),
    }
    schemes = {
        "official": SchemeSpec(
            "official", "official", source=_SPLITS_FILE, rationale="the publisher's split"
        ),
        "ident-72-14-14": SchemeSpec("ident-72-14-14", "derived", rationale="identity carve"),
        "all-test": SchemeSpec("all-test", "subset", rationale="every video is test"),
        "benchmark": SchemeSpec("benchmark", "subset", rationale="a small balanced test set"),
    }
    default_scheme = "official"
    benchmark = BenchmarkSpec(k_fake=2)
    pairing_rule = "target-id"
    card_info = {
        "name": "Pack Demo",
        "release": "1",
        "homepage": "https://example.org/packdemo",
        "license": {"spdx": None, "summary": "synthetic test data"},
        "access": "generated by the tests",
        "modalities": ["video"],
        "compressions": None,
        "key_rule": "<task>/<file stem>",
    }

    def record_for_video(
        self, task: TaskSpec, path: Path, relpath: str, compression: str | None
    ) -> InventoryRecord | None:
        stem = path.stem
        if task.kind == "real":
            return self.record(task, stem, relpath, compression, identity=stem, target_id=stem)
        target, _, source = stem.partition("_")
        return self.record(
            task,
            stem,
            relpath,
            compression,
            identity=target,
            target_id=target,
            source_id=source,
            pair_key=target,
        )

    def official_splits(self, root: Path, records: Sequence[InventoryRecord]) -> dict[str, Split]:
        path = root / _SPLITS_FILE
        if not path.is_file():
            raise ConfigError(f"packdemo: {path} is missing", hint="write splits.json")
        listed = json.loads(path.read_text("utf-8"))
        by_identity = {ident: split for split, idents in listed.items() for ident in idents}
        return {r.key: by_identity[r.identity] for r in records if r.identity in by_identity}

    def pair_candidates(self, fake: InventoryRecord) -> str | None:
        return fake.target_id


