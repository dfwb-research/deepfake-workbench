def make_packdemo_tree(folder: Path) -> Path:
    """The raw release: 10 reals, 10 fakes per method, and the official split file."""
    for index, identity in enumerate(_IDENTITIES):
        for directory, stem in (
            ("originals", identity),
            ("swap_a", f"{identity}_{_IDENTITIES[(index + 1) % 10]}"),
            ("swap_b", f"{identity}_{_IDENTITIES[(index + 2) % 10]}"),
        ):
            (folder / directory).mkdir(parents=True, exist_ok=True)
            (folder / directory / f"{stem}.mp4").touch()
    (folder / _SPLITS_FILE).write_text(
        json.dumps({split: list(ids) for split, ids in _OFFICIAL.items()}), "utf-8"
    )
    return folder


def make_pack_root(tmp_path: Path) -> Path:
    """An importable, empty pack (``datasets: []``); returns the directory holding pack.yaml."""
    package = tmp_path / "dfwb_packdemo_fixture"
    root = package / "pack"
    root.mkdir(parents=True)
    (package / "__init__.py").write_text("")
    (root / "pack.yaml").write_text(
        "schema_version: 1\nname: packdemo-pack\nversion: 1.0.0\ndatasets: []\n", "utf-8"
    )
    return root


def setup_packdemo(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path, *, register_pack: bool = True
) -> dict[str, Path]:
    """Roots, the raw release, a built inventory and an empty registered pack."""
    monkeypatch.chdir(tmp_path)
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    monkeypatch.setenv("XDG_CONFIG_HOME", str(tmp_path / "home" / ".config"))
    for name in list(os.environ):
        if name.startswith("DFWB_"):
            monkeypatch.delenv(name)
    raw, work = tmp_path / "raw", tmp_path / "work"
    monkeypatch.setenv("DFWB_DATASETS_ROOT", str(raw))
    monkeypatch.setenv("DFWB_WORK_ROOT", str(work))
    make_packdemo_tree(raw / "PackDemo")
    pack = make_pack_root(tmp_path)
    install(
        monkeypatch,
        {
            "packdemo": (PACKDEMO_TARGET, "Pack Demo", "PackDemo"),
            "packdemo-carve": (f"{_MODULE}:PackDemoCarveBuilder", "Pack Demo Carve", "PackDemo"),
            "packdemo-valonly": (f"{_MODULE}:PackDemoValOnlyBuilder", "Val Only", "PackDemo"),
            "packdemo-noofficial": (
                f"{_MODULE}:PackDemoNoOfficialBuilder",
                "No Official",
                "PackDemo",
            ),
        },
        packs={PACK_NAME: pack} if register_pack else None,
    )
    inventory = build_inventory("packdemo").path
    return {"raw": raw, "work": work, "pack": pack, "inventory": inventory}


@pytest.fixture
def demo(monkeypatch: pytest.MonkeyPatch, tmp_path: Path) -> dict[str, Path]:
    return setup_packdemo(monkeypatch, tmp_path)


def _files(folder: Path) -> dict[str, bytes]:
    return {
        path.relative_to(folder).as_posix(): path.read_bytes()
        for path in sorted(folder.rglob("*"))
        if path.is_file()
    }


