def test_output_inside_an_overridden_dataset_folder_is_refused(demo, monkeypatch, tmp_path):
    elsewhere = tmp_path / "elsewhere" / "PackDemo"
    elsewhere.parent.mkdir()
    (demo["raw"] / "PackDemo").rename(elsewhere)
    monkeypatch.setenv("DFWB_DATASET_PACKDEMO", str(elsewhere))

    with pytest.raises(ConfigError) as info:
        build_dataset("packdemo", out=elsewhere / "packdemo")
    assert "dataset folder" in info.value.message

    # The override is where the publisher's split is read from, too.
    assert locate_metadata_root(get_builder("packdemo")) == elsewhere


