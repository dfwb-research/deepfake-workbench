def test_build_is_byte_reproducible(demo, tmp_path):
    first = build_dataset("packdemo", out=tmp_path / "a" / "packdemo")
    build_dataset("packdemo", out=tmp_path / "b" / "packdemo")
    # The inventory's row order never matters: the same rows, reversed, give the same bytes.
    rows = read_inventory("packdemo", demo["work"])
    reversed_inventory = tmp_path / "reversed.jsonl"
    write_jsonl(reversed_inventory, list(reversed(rows)))
    build_dataset("packdemo", out=tmp_path / "c" / "packdemo", inventory=reversed_inventory)
    # Rebuilding in place changes nothing either.
    build_dataset("packdemo", out=first.out)

    a = _files(tmp_path / "a" / "packdemo")
    assert a == _files(tmp_path / "b" / "packdemo")
    assert a == _files(tmp_path / "c" / "packdemo")
    assert str(tmp_path) not in "".join(v.decode("utf-8", "replace") for v in a.values())


def test_scheme_card_has_rule_params_counts_and_hash(demo):
    out = demo["pack"] / "packdemo"
    result = build_dataset("packdemo", out=out)

    card = read_card(out)
    assert card.schemes == result.schemes
    assert card.default_scheme == "official"
    assert card.distribution == "undecided"

    official = result.schemes["official"]
    assert (official.kind, official.rule, official.source) == (
        "official",
        "official",
        "splits.json",
    )
    assert official.rationale == "the publisher's split"
    assert official.params == {}
    assert official.counts == {"test": 6, "train": 18, "val": 6}
    for name, scheme in result.schemes.items():
        rows = read_split_tsv(out / "splits" / f"{name}.tsv.gz")
        assert scheme.sha256 == split_sha256(rows)
        assert sum((scheme.counts or {}).values()) == len(rows)

    carve = result.schemes["ident-72-14-14"]
    assert (carve.kind, carve.rule, carve.params) == ("derived", "ident-72-14-14", {})
    assert sum((carve.counts or {}).values()) == 30
    assert result.schemes["all-test"].counts == {"test": 30}

    benchmark = result.schemes["benchmark"]
    assert (benchmark.kind, benchmark.rule) == ("subset", "benchmark")
    assert benchmark.params == {
        "k_fake": 2,
        "strata": [],
        "k_real_cap": None,
        "exclude_tasks": [],
        "seed": 0,
        "task_order": ["REAL", "FS_A", "FS_B"],
        "pool": "official-test",
        "compressions": None,
    }
    assert benchmark.counts == {"test": 4}


